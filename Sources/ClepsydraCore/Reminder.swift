import Foundation

/// Оклик тому, кто сидит за Mac и не запустил сессию. Второй голос
/// приложения — узкий, выключенный по умолчанию и ограниченный уставом,
/// см. ADR-0014.
///
/// Чистый тип, как и автомат: ни уведомлений, ни системного времени, ни IOKit
/// внутри — момент и время последнего касания приходят снаружи параметром.
/// Разрешение, центр уведомлений и счётчик простоя живут снаружи, в
/// `Reminders`.
public struct Reminder {

    /// Раз в пятнадцать минут простоя. Срок один и из списка не выбирается,
    /// в отличие от длительностей (ADR-0011): он не отличается для того, кто
    /// работает с почтой, и для того, кто пишет код.
    public static let interval: TimeInterval = 15 * 60

    /// Порог присутствия: сколько может пройти с последнего касания
    /// клавиатуры или мыши, чтобы за Mac всё ещё считался человек.
    ///
    /// Заметно короче срока нарочно. Будь он вровень с пятнадцатью минутами,
    /// оклик отменялся бы у тех, кто за Mac и просто не печатает в эту
    /// секунду. Ошибается порог в сторону молчания: непришедший оклик стоит
    /// меньше, чем оклик в пустую комнату.
    public static let presence: TimeInterval = 5 * 60

    /// Когда придёт следующий оклик. Дата, а не остаток, — по той же причине,
    /// что у помидора: пока Mac спит, считать нечем, а дата остаётся верной.
    private var due: Date

    /// Когда правило спрашивали в прошлый раз. Тик приходит раз в секунду, и
    /// разрыв между тиками — единственное, по чему видно, что Mac спал. Мерить
    /// опоздание от срока для этого нельзя: сон, кончившийся в самый срок,
    /// опоздания не даёт вовсе.
    private var lastTick: Date

    public init(from now: Date) {
        due = now + Self.interval
        lastTick = now
    }

    /// Отсчёт заново — от этого момента.
    public mutating func restart(at now: Date) {
        due = now + Self.interval
        lastTick = now
    }

    /// Тик. `true` — пора окликнуть.
    ///
    /// Висит на том же секундном тике, что и отсчёт в меню-баре: вопрос к
    /// правилу тот же — сколько прошло.
    public mutating func advance(to now: Date, phase: Phase, idleFor idle: TimeInterval) -> Bool {
        // Разрыв между тиками больше минуты — Mac спал, а не подтормозил: та
        // же мерка, которой автомат отличает сон (ADR-0002). Часы, отмотанные
        // назад, — тот же случай: срок назначен не этими часами.
        //
        // Меряется разрыв, а не опоздание от срока. Сон длиной ровно в срок
        // опоздания не даёт вовсе — проснулись бы под баннер про пятнадцать
        // минут, прошедших во сне, а это тот же «пора отдохнуть» человеку,
        // который час как отдохнул.
        let slept = now < lastTick || now > lastTick + TimerMachine.overdueGrace
        lastTick = now

        // Простой — единственное состояние, в котором есть о чём окликать.
        // Идёт помидор, идёт перерыв или висит экран ожидания — отсчёт стоит
        // на пятнадцати минутах и начнётся заново, когда круг кончится. Этим
        // же держатся «после запуска сессии», «после сброса» и «после
        // „Хватит“»: любая дорога в простой ведёт через фазу, которая не он.
        //
        // Проснулись — считаем заново: пропущенные за ночь оклики пачкой не
        // выдаются.
        guard case .idle = phase, !slept else {
            restart(at: now)
            return false
        }

        guard now >= due else { return false }

        // Пропущенный оклик ничего не откладывает: следующая попытка — через
        // пятнадцать минут от предыдущей, а не через пятнадцать минут после
        // возвращения. Иначе отлучка за кофе отодвигала бы напоминание тем
        // дальше, чем дольше человека нет, — то есть ровно наоборот.
        due += Self.interval

        // Окликают присутствующего. Доказательством присутствия касание не
        // является — человек читает с экрана, сидит на созвоне, — но других
        // дешёвых оценок у приложения нет.
        return idle <= Self.presence
    }
}

/// Что пункт меню знает про напоминание прямо сейчас. Лиц у пункта, как у
/// пункта обновления, больше одного.
public enum ReminderState: Equatable {
    /// Выключено — так стоит по умолчанию и после повторного щелчка.
    case off
    /// Включено и разрешено: напоминание работает.
    case on
    /// Включено, но система говорить не даёт: разрешение отозвали в системных
    /// настройках, и приложению об этом никто не сообщил. Галочка тут была бы
    /// враньём, см. ADR-0014.
    case silenced
}

/// Как напоминание называется словами: пункт меню и само уведомление. Живёт
/// рядом с состоянием, а не в контроллере меню: слова — часть решения, и
/// проверяются они здесь же, без AppKit.
public enum ReminderLabel {

    /// Строка пункта меню. Включённый и выключенный зовутся одинаково —
    /// разницу показывает галочка, как у «Запускать при входе». Третье лицо
    /// зовёт туда, где запрет и снимают: внутри приложения его чинить нечем.
    public static func menu(for state: ReminderState) -> String {
        switch state {
        case .off, .on: return "Напоминать о сессии"
        case .silenced: return "Разрешить напоминания в системе"
        }
    }

    /// Стоит ли галочка. Отдельно от строки: включённым пункт считается,
    /// только когда напоминание вправду говорит.
    public static func isOn(_ state: ReminderState) -> Bool {
        state == .on
    }

    /// Что написано в уведомлении. Одно предложение, и другого не будет: ни
    /// счёта за день, ни вчерашнего сравнения, ни версии — устав узкий
    /// нарочно. Помидор здесь называется сессией, как в меню и на экране.
    public static let notice = "Сессия не запущена"

    /// Кнопка в уведомлении. Глагол, как «Отдохнуть» на экране.
    public static let noticeAction = "Запустить"
}
