#!/bin/bash
# Собирает архив, которым обновление ставится на месте, и печатает его имя.
#
#   ./Tools/update-archive.sh --name              имя архива в релизе
#   ./Tools/update-archive.sh Clepsydra.app       собирает архив в корне репозитория
#
# Бандл называют от корня репозитория, а не от рабочей папки: скрипт туда
# переходит сам, как остальные в Tools/.
#
# Почему zip, а не образ: образ человек монтирует и перетаскивает руками, а
# этот файл разворачивает установщик. Имя без версии — как у образа: адрес
# архива приходит из фида, но короткое имя проще узнать в списке релиза.
#
# ditto, а не zip: сохраняет структуру бандла, права и подпись. Пересобранный
# обычным zip бандл теряет символические ссылки внутри фреймворка, и подпись
# после распаковки не сходится.
set -euo pipefail
cd "$(dirname "$0")/.."

ARCHIVE_NAME=Clepsydra.zip

# Имя знает и приложение — из него собирается адрес архива в фиде.
if [[ "${1:-}" == "--name" ]]; then
    echo "$ARCHIVE_NAME"
    exit 0
fi

APP="${1:-}"

if [[ -z "$APP" || ! -d "$APP" ]]; then
    echo "ОШИБКА: нет бандла ${APP:-— он не назван}." >&2
    exit 1
fi

rm -f "$ARCHIVE_NAME"
ditto -c -k --keepParent "$APP" "$ARCHIVE_NAME"

echo "$ARCHIVE_NAME"
