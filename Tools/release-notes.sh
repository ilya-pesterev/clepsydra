#!/bin/bash
# Печатает описание релиза: что изменилось, требования и первый запуск.
#
# Что изменилось пишется руками и приходит файлом — из docs/releases/<версия>.md.
# Остальное от релиза к релизу не меняется и живёт здесь: абзац про первый
# запуск забыть проще всего, а без него человек решит, что скачал сломанное
# приложение.
#
#   ./Tools/release-notes.sh docs/releases/1.0.md
#   ./Tools/release-notes.sh docs/releases/1.0.md путь/Info.plist   для тестов
set -euo pipefail
cd "$(dirname "$0")/.."

CHANGES="${1:-}"
PLIST="${2:-Resources/Info.plist}"

if [[ -z "$CHANGES" || ! -f "$CHANGES" ]]; then
    echo "ОШИБКА: нет файла с описанием изменений: ${CHANGES:-не назван}." >&2
    echo "Напишите, что изменилось, и положите в docs/releases/<версия>.md." >&2
    exit 1
fi

if [[ -z "$(tr -d '[:space:]' < "$CHANGES")" ]]; then
    echo "ОШИБКА: в $CHANGES пусто — релиз без «что изменилось» никому не нужен." >&2
    exit 1
fi

# Имя образа собирает dmg-name.sh: в описании файл должен называться ровно так
# же, как лежит в релизе.
DMG="$(./Tools/dmg-name.sh "$PLIST")"

cat "$CHANGES"

cat <<MARKDOWN

## Что нужно

Mac на Apple Silicon и macOS 14 или новее.

## Установка

Скачайте \`$DMG\`, откройте двойным щелчком и перетащите иконку Clepsydra на
ярлык «Applications». Терминал не нужен ни разу.

Файл доехал целиком, если рядом со скачанным образом

\`\`\`bash
shasum -a 256 -c $DMG.sha256
\`\`\`

отвечает \`$DMG: OK\`. Оба файла лежат ниже.

## Первый запуск

Сборка подписана ad-hoc: сертификата Apple Developer ID у проекта нет, а
значит, нет и нотаризации. Поэтому первый двойной щелчок macOS остановит окном
«Файл «Clepsydra» не был открыт». Синяя кнопка по умолчанию в нём —
«Переместить в Корзину», не нажимайте Enter не глядя: нажмите «Готово».

Дальше  → «Системные настройки…» → «Конфиденциальность и безопасность»,
раздел «Безопасность»: рядом со строкой про заблокированный файл будет кнопка
«Все равно открыть». Второй запуск переспросит в последний раз — «Открыть».
Больше приложение ни о чём не спросит.

Весь путь целиком, вместе с английскими названиями окон, —
в [docs/install.md](https://github.com/ilya-pesterev/clepsydra/blob/main/docs/install.md).
MARKDOWN
